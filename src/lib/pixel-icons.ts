export const PIXEL_EXPORT_SIZES = [16, 24, 32, 48, 64, 128, 256, 512] as const;

export type PixelExportSize = (typeof PIXEL_EXPORT_SIZES)[number];
export type PixelExportFormat = "svg" | "png" | "webp";

export function buildPixelSvg(icon: PixelIcon, size: number, color: string): string {
  const rects: string[] = [];
  icon.rows.forEach((row, y) => {
    for (let x = 0; x < PIXEL_ICON_SIZE; x += 1) {
      if (row[x] === X) {
        rects.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`);
      }
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges"><g fill="${color}">${rects.join("")}</g></svg>`;
}